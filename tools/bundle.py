#!/usr/bin/env python3
"""Flatten src/claude_usage into the single-file plugin at plugin/claude-usage.1m.py.

Why one file: SwiftBar and Argos run every file in their plugin folder, and installs from
v1.2.x self-update by downloading exactly that path and checking that it starts with
`#!/usr/bin/python3`, contains `VERSION = "X.Y.Z"` and compiles. The flat file stays readable,
so a user can audit what reads their credentials.

Rules for src/claude_usage (enforced here):
- sibling imports only as `from .module import name, ...` (removed when flattening),
- top-level names unique across modules,
- no OS-specific work at import time (Windows/GTK imports go inside functions).

Usage: tools/bundle.py              write the plugin
       tools/bundle.py --check      exit 1 if the committed plugin is stale
       tools/bundle.py --out PATH   write the bundle somewhere else (scratch builds)
"""
from __future__ import annotations

import ast
import os
import sys
from typing import Dict, List, Set, Tuple

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "src", "claude_usage")
OUT = os.path.join(ROOT, "plugin", "claude-usage.1m.py")
SKIP = {"__init__.py", "__main__.py"}

HEADER = '''#!/usr/bin/python3
# <xbar.title>Claude Code usage</xbar.title>
# <xbar.desc>5-hour and weekly plan usage for every Claude Code account on this computer.</xbar.desc>
# <xbar.dependencies>python3</xbar.dependencies>
#
# GENERATED by tools/bundle.py from src/claude_usage/. Do not edit this file; edit the
# sources and run ./build.sh.
#
# macOS: Apple's /usr/bin/python3 on purpose, it trusts the system certificate store.
# Linux (GNOME): runs as an Argos plugin. Windows and other Linux desktops: run with --tray.
# Optional ~/.config/claude-usage.conf, one entry per line:
#   label = /path/to/token-file     add a token the scan cannot find
#   keychain = off                  hide browser logins
from __future__ import annotations
'''
FOOTER = '''

if __name__ == "__main__":
    import sys
    sys.exit(main())
'''


def modules() -> Dict[str, ast.Module]:
    result = {}
    for name in sorted(os.listdir(SRC)):
        if name.endswith(".py") and name not in SKIP:
            with open(os.path.join(SRC, name), encoding="utf-8") as f:
                result[name[:-3]] = ast.parse(f.read(), name)
    return result


def sibling_deps(tree: ast.Module) -> Set[str]:
    deps = set()
    for node in ast.walk(tree):
        if isinstance(node, ast.ImportFrom) and node.level:
            if node.level != 1 or not node.module:
                raise SystemExit("only `from .module import ...` is allowed (line %d)" % node.lineno)
            deps.add(node.module)
    return deps


def order(trees: Dict[str, ast.Module]) -> List[str]:
    """Modules in dependency order. Imports inside functions are lazy, so only top-level
    sibling imports constrain the order."""
    top = {}
    for name, tree in trees.items():
        sibling_deps(tree)  # validates every sibling import, nested ones too
        top[name] = {n.module for n in tree.body if isinstance(n, ast.ImportFrom) and n.level}
    done: List[str] = []
    visiting: Set[str] = set()

    def visit(name: str):
        if name in done:
            return
        if name in visiting:
            raise SystemExit("import cycle through %s" % name)
        if name not in trees:
            raise SystemExit("unknown sibling module %s" % name)
        visiting.add(name)
        for dep in sorted(top[name]):
            visit(dep)
        visiting.discard(name)
        done.append(name)

    for name in sorted(trees):
        visit(name)
    return done


def top_level_names(tree: ast.Module) -> Tuple[Set[str], Dict[str, str]]:
    """(names defined, names imported -> what they refer to)."""
    defined, imported = set(), {}
    for node in tree.body:
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
            defined.add(node.name)
        elif isinstance(node, (ast.Assign, ast.AnnAssign)):
            targets = node.targets if isinstance(node, ast.Assign) else [node.target]
            for t in targets:
                for n in ast.walk(t):
                    if isinstance(n, ast.Name):
                        defined.add(n.id)
        elif isinstance(node, ast.Import):
            for a in node.names:
                imported[a.asname or a.name.split(".")[0]] = a.name
        elif isinstance(node, ast.ImportFrom) and not node.level and node.module != "__future__":
            for a in node.names:
                imported[a.asname or a.name] = node.module + "." + a.name
        elif isinstance(node, ast.Try):  # e.g. optional imports
            for sub in node.body:
                if isinstance(sub, (ast.Import, ast.ImportFrom)):
                    raise SystemExit("keep imports out of try blocks at top level")
    return defined, imported


def check_names(trees: Dict[str, ast.Module]) -> None:
    owner: Dict[str, str] = {}
    bindings: Dict[str, Tuple[str, str]] = {}
    for mod, tree in trees.items():
        defined, imported = top_level_names(tree)
        for n in defined:
            if n in owner:
                raise SystemExit("top-level name %r defined in both %s and %s" % (n, owner[n], mod))
            if n in bindings:
                raise SystemExit("%s.%s shadows an import in %s" % (mod, n, bindings[n][0]))
            owner[n] = mod
        for n, target in imported.items():
            if n in owner:
                raise SystemExit("import %r in %s shadows a name from %s" % (n, mod, owner[n]))
            if n in bindings and bindings[n][1] != target:
                raise SystemExit("%r means %s in %s but %s in %s"
                                 % (n, bindings[n][1], bindings[n][0], target, mod))
            bindings.setdefault(n, (mod, target))


def flatten(name: str, tree: ast.Module) -> str:
    with open(os.path.join(SRC, name + ".py"), encoding="utf-8") as f:
        lines = f.read().splitlines()
    for node in ast.walk(tree):
        if isinstance(node, ast.ImportFrom) and (node.level or node.module == "__future__"):
            first, last = node.lineno - 1, node.end_lineno - 1
            indent = lines[first][:len(lines[first]) - len(lines[first].lstrip())]
            # A nested import becomes `pass` so the block stays valid; the name is global now.
            lines[first] = indent + "pass" if indent else ""
            for i in range(first + 1, last + 1):
                lines[i] = ""
    body = "\n".join(lines).strip("\n")
    while "\n\n\n\n" in body:
        body = body.replace("\n\n\n\n", "\n\n\n")
    return "\n\n# " + "-" * 10 + " claude_usage/%s.py " % name + "-" * 10 + "\n\n" + body + "\n"


def bundle() -> str:
    trees = modules()
    check_names(trees)
    text = HEADER + "".join(flatten(n, trees[n]) for n in order(trees)) + FOOTER
    compile(text, OUT, "exec")
    return text


def main() -> int:
    text = bundle()
    args = sys.argv[1:]
    out = OUT
    if len(args) == 2 and args[0] == "--out":
        out = args[1]
    elif args == ["--check"]:
        with open(OUT, encoding="utf-8") as f:
            if f.read() != text:
                print("plugin/claude-usage.1m.py is stale: run ./build.sh", file=sys.stderr)
                return 1
        return 0
    elif args:
        print(__doc__, file=sys.stderr)
        return 2
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    os.chmod(out, 0o755)
    return 0


if __name__ == "__main__":
    sys.exit(main())
